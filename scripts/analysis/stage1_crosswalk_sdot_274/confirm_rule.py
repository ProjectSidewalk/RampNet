"""Which free signals confirm a crowd Crosswalk label where a city has no inventory? Calibrated in Seattle (RampNet#274).

Project Sidewalk's stores hold ~57k crowd Crosswalk labels on ~31k panos across nine cities (Chicago alone 28k),
but only Seattle has a GT-grade inventory and most labels are `undecided` (fewer than two net human votes). This
script fixes, in Seattle where SDOT is truth, the rule that decides which crowd labels become training positives
elsewhere.

THE RULE, fixed 2026-11-03 BEFORE arm C's Vistas readings (`crowd_arm.py place`) were looked at:
  Population: Seattle crowd Crosswalk labels on stored panos (arm C `selection.csv`) not voted incorrect, inside
  SDOT coverage (some SDOT point of any status within 100 m of the label; the amended rule's mask).
  Truth: a current SDOT point within 10 m of the label (SDOT's own sensitivity inside coverage is 0.961 on the
  Phase 0 human rows, so even a perfect rule reads ~0.96 here).
  Signals, each free in every city:
    V  validated: human agree - disagree >= 2
    O  an OSM marked-or-signalised crossing node within 10 m of the label
    P  Vistas crosswalk paint at the click's exact pixel (arm C `placements.csv`, `on_paint`)
    T  Vistas crosswalk paint within 0.022 pano width of the click (RampNet's matcher radius)
  Candidate rules: V, O, P, T, V|O, V|P, V|T, O&P, O&T, V|(O&P), V|(O&T).
  A rule PASSES when its precision against SDOT is >= 0.90 with Wilson lower bound >= 0.88 (about 6 points
  under SDOT's ceiling). Among passing rules the ADOPTED one has the highest yield (share of the population it
  keeps); ties go to the simpler rule (fewer signals). If none passes, the reading is "no free confirmer", and
  only V-labels are used outside Seattle, reported as such.
  Per-year precision is reported beside it (temporal alignment), never used for the verdict.

  python confirm_rule.py --crowd analysis_out/stage1_crosswalk_crowd_274 \
      --inventory <crosswalk-inventory-274>/analysis_out/crosswalk_inventory_274 --census <Phase 0 census OUT>
Writes `confirm_rule.md` into --crowd.
"""
import argparse
import csv
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from pilot import (TOL_R, Grid, all_sdot_points, frac, load_inventory, osm_marked_nodes, wilson)  # noqa: E402

RULE = {"precision_min": 0.90, "wilson_lo_min": 0.88, "coverage_m": 100.0, "match_m": 10.0, "fixed": "2026-11-03",
        "candidates": ["V", "O", "P", "T", "V|O", "V|P", "V|T", "O&P", "O&T", "V|(O&P)", "V|(O&T)"]}


def evaluate(expr, s):
    """Evaluate a rule string over a dict of booleans, e.g. 'V|(O&P)'."""
    return bool(eval(expr.replace("|", " or ").replace("&", " and "), {}, s))  # noqa: S307 -- fixed literals only


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--crowd", required=True)
    ap.add_argument("--inventory", required=True)
    ap.add_argument("--census", required=True)
    a = ap.parse_args()
    _, feats, _ = load_inventory(a.inventory)
    allp = all_sdot_points(feats)
    g_all = Grid(allp)
    g_osm = Grid(osm_marked_nodes(a.census))
    sel = {r["label_uid"]: r for r in csv.DictReader(open(os.path.join(a.crowd, "selection.csv"), encoding="utf-8"))}
    pl = {}
    for r in csv.DictReader(open(os.path.join(a.crowd, "placements.csv"), encoding="utf-8")):
        if r["kind"].startswith("crowd_"):
            pl[r["id"]] = r
    rows = []
    for uid, s in sel.items():
        if s["verdict"] == "incorrect" or uid not in pl:
            continue
        lat, lng = float(s["label_lat"]), float(s["label_lng"])
        if not g_all.within(lat, lng, RULE["coverage_m"]):
            continue
        p = pl[uid]
        near = float(p["near_px_dist"]) if p["near_px_dist"] else None
        sig = {"V": s["verdict"] == "correct", "O": bool(g_osm.within(lat, lng, RULE["match_m"])),
               "P": p["on_paint"] == "1", "T": near is not None and near <= TOL_R}
        truth = bool(s["d_sdot_m"]) and float(s["d_sdot_m"]) <= RULE["match_m"]
        rows.append((uid, sig, truth, (s["image_capture_date"] or "")[:4]))
    L = []
    w = L.append
    w("# Confirming crowd Crosswalk labels without an inventory: the Seattle calibration (RampNet#274)\n")
    w(f"Generated by `scripts/analysis/stage1_crosswalk_sdot_274/confirm_rule.py`. Rule fixed {RULE['fixed']} before "
      f"arm C's Vistas readings were looked at (see the docstring). Population: {len(rows)} crowd labels not voted "
      f"incorrect, on stored panos, inside SDOT coverage; base rate (SDOT confirms) "
      f"{frac(sum(t for _, _, t, _ in rows), len(rows))}.\n")
    w("| rule | keeps | yield | precision vs SDOT | passes |\n|---|---|---|---|---|")
    res = []
    for expr in RULE["candidates"]:
        kept = [t for _, s, t, _ in rows if evaluate(expr, s)]
        k, n = sum(kept), len(kept)
        lo = wilson(k, n)[0] if n else 0.0
        ok = n > 0 and k / n >= RULE["precision_min"] and lo >= RULE["wilson_lo_min"]
        res.append((expr, n, k, ok))
        w(f"| `{expr}` | {n} | {n / len(rows):.3f} | {frac(k, n)} | {'yes' if ok else 'no'} |")
    passing = [r for r in res if r[3]]
    w("")
    if passing:
        best = max(passing, key=lambda r: (r[1], -len([c for c in r[0] if c.isalpha()])))
        w(f"**Adopted: `{best[0]}`** — keeps {best[1]} of {len(rows)} ({best[1] / len(rows):.3f}) at precision "
          f"{frac(best[2], best[1])}.\n")
        expr = best[0]
    else:
        w("**No free confirmer passes**; outside Seattle only validated (V) labels are used.\n")
        expr = "V"
    w(f"Precision of `{expr}` by capture year (reported, not the verdict):\n")
    w("| year | keeps | precision |\n|---|---|---|")
    for y in sorted({yy for _, _, _, yy in rows if yy}):
        kept = [t for _, s, t, yy in rows if yy == y and evaluate(expr, s)]
        w(f"| {y} | {len(kept)} | {frac(sum(kept), len(kept))} |")
    with open(os.path.join(a.crowd, "confirm_rule.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {a.crowd}/confirm_rule.md")


if __name__ == "__main__":
    main()
