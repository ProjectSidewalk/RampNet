"""#276 follow-up A: the whole-prompt-rewrite arm, scored on the dev split.

Step 4 let a critic rewrite only the class DEFINITION and came out null. This arm lets
it rewrite the WHOLE instruction (``--prompt-body``, ``prompt_optimize.py --scope prompt``),
reusing the crops Jon confirmed in Step 4, with an image-free paraphrase as the control
(``prompt276-<model>-alt``).

Two numbers per candidate, both from the local detection cache:

* ``dev_train`` F1, as the optimizer recorded it in
  ``benchmark/prompt_opt_276/optimize/<model>/prompt/trajectory.jsonl`` -- the loop's own
  accept/reject test against the seed, with the model's noise floor.
* ``dev_select`` F1 at the threshold selected on dev_select (Step 5's procedure), next to
  the existing arms {zs, para3, expert}. The pre-registered gate for a held-out run is
  >= 0.02 F1 over the best existing arm AND above the image-free control.

    python scripts/analysis/prompt_276_rewrite.py --cache-dir <main checkout>/.model_cache
    python scripts/analysis/prompt_276_rewrite.py --check --cache-dir ...
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
sys.path.insert(0, REPO_ROOT)

import prompt_276_heldout as H          # noqa: E402

C, D = H.C, H.D
OUT_JSON = os.path.join(H.OUT_DIR, "rewrite_arm.json")
OUT_MD = os.path.join(H.OUT_DIR, "rewrite_arm.md")
GATE = 0.02
EXISTING = (("zs", None), ("para3", "para3"), ("expert", "expert"))
CANDIDATES = ("r1", "r2", "alt")
OPT_DIR = os.path.join(REPO_ROOT, "benchmark", "prompt_opt_276", "optimize")


def trajectory(model_id):
    """{candidate name: the optimizer's evaluation row} from the prompt-scope record."""
    path = os.path.join(OPT_DIR, model_id, "prompt", "trajectory.jsonl")
    rows = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            row = json.loads(line)
            if row.get("kind") == "seed":
                rows["__seed__"] = row
            elif row.get("prompt_body"):
                rows[row["prompt_body"]] = row
    return rows


def build(cache_dir):
    rsq = H.radius_sq_for()
    cache = C.DetectionCache(cache_dir, enabled=True)
    args = H._compare_args(cache_dir)
    args.gemini_confidence = True
    args.gemini_thinking_level = None
    with open(os.path.join(REPO_ROOT, H.SPLIT_FILE), encoding="utf-8") as f:
        dev_select = json.load(f)["dev_select"]
    records, verdicts, _ = C.load_bundle(os.path.join(REPO_ROOT, "benchmark", H.DEV_CITY))
    gts_all = C.ground_truths_from_verdicts(records, verdicts)
    gts = {p: gts_all[p] for p in dev_select}

    def score(model_id, definition, body):
        args.definition, args.prompt_body = definition, body
        label, det = D.build_detector("gemini", model_id, records, args)
        pts, missing = H.cached_points(cache, label, det.signature(), H.DEV_CITY, dev_select)
        assert not missing, (model_id, definition, body, len(missing))
        thr, f1, _ = H.select_threshold(pts, gts, rsq)
        raw = H.f1_from_counts(*H.pano_counts(pts, gts, rsq, 0.0).sum(0))
        return {"threshold": thr, "dev_select_f1": f1, "dev_select_f1_raw": round(float(raw), 4)}

    models = []
    for model_id, short in H.MODELS:
        traj = trajectory(model_id)
        existing = {arm: score(model_id, d, None) for arm, d in EXISTING}
        best_arm = max(existing, key=lambda a: existing[a]["dev_select_f1"])
        best = existing[best_arm]["dev_select_f1"]
        cands = {}
        for c in CANDIDATES:
            name = "prompt276-%s-%s" % (short, c)
            row = score(model_id, None, name)
            t = traj.get(name, {})
            row["name"] = name
            if t.get("kind") == "evaluate":      # the control is never scored on dev_train
                row["dev_train"] = {"f1": t["train_f1"], "seed_f1": traj["__seed__"]["train_f1"],
                                    "gain": t["gain"], "floor": t["floor"],
                                    "accepted": t["accepted"]}
            row["delta_vs_best_existing"] = round(row["dev_select_f1"] - best, 4)
            cands[c] = row
        control = cands["alt"]["dev_select_f1"]
        for c in ("r1", "r2"):
            cands[c]["passes_gate"] = bool(cands[c]["delta_vs_best_existing"] >= GATE
                                           and cands[c]["dev_select_f1"] > control)
        models.append({"model": model_id, "short": short, "existing": existing,
                       "best_existing": best_arm, "candidates": cands})
    return {"gate": GATE, "n_panos": len(dev_select), "models": models}


def render_md(res):
    lines = ["# #276 follow-up: whole-prompt-rewrite arm on the dev split", "",
             "Generated by `scripts/analysis/prompt_276_rewrite.py`. Do not edit by hand.", "",
             "dev_select F1 (%d panos) at the threshold selected on dev_select; the gate is "
             "+%.2f over the best existing arm and above the image-free control."
             % (res["n_panos"], res["gate"]), "",
             "| Model | Prompt | Threshold | dev_select F1 | vs best existing | Gate "
             "| dev_train F1 (seed) | Optimizer |",
             "|---|---|---|---|---|---|---|---|"]
    for m in res["models"]:
        for arm, r in m["existing"].items():
            mark = " (best existing)" if arm == m["best_existing"] else ""
            lines.append("| %s | %s%s | %.2f | %.3f | | | | |" % (
                m["model"], arm, mark, r["threshold"], r["dev_select_f1"]))
        for c in ("alt", "r1", "r2"):
            r = m["candidates"][c]
            gate = "control" if c == "alt" else ("PASS" if r["passes_gate"] else "fail")
            dt = r.get("dev_train")
            train = ("%.3f (%.3f) | %s" % (dt["f1"], dt["seed_f1"],
                                           "accepted" if dt["accepted"] else "rejected")
                     if dt else " | ")
            lines.append("| %s | %s | %.2f | %.3f | %+.3f | %s | %s |" % (
                m["model"], r["name"], r["threshold"], r["dev_select_f1"],
                r["delta_vs_best_existing"], gate, train))
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cache-dir", default=os.path.join(REPO_ROOT, ".model_cache"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    res = build(args.cache_dir)
    rel = os.path.relpath(OUT_JSON, REPO_ROOT).replace("\\", "/")
    if args.check:
        with open(OUT_JSON, encoding="utf-8") as f:
            committed = json.load(f)
        if committed != res:
            print("MISMATCH: %s does not reproduce from the cache" % rel)
            return 1
        print("OK: %s reproduces from the cache" % rel)
        return 0
    os.makedirs(H.OUT_DIR, exist_ok=True)
    with open(OUT_JSON, "w", encoding="utf-8", newline="\n") as f:
        json.dump(res, f, indent=1)
        f.write("\n")
    with open(OUT_MD, "w", encoding="utf-8", newline="\n") as f:
        f.write(render_md(res))
    print(render_md(res))
    return 0


if __name__ == "__main__":
    sys.exit(main())
