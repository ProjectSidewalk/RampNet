"""#276 Step 6: the in-context-images control (four exemplar crops in the prompt).

Rewording the class definition moved the Gemini models little (Steps 3-5). This control
asks whether SHOWING them examples does more: the prompt gets four labelled crops before
the query image -- two curb ramps the models missed and two look-alikes they boxed, the
iter_01 picks Jon confirmed in Step 4 (``benchmark/prompt_opt_276/exemplars/shared4.json``,
the same set for both models) -- plus the confidence request of every Step 5 arm.

Scored exactly as Step 5 (helpers imported from ``prompt_276_heldout``): the arm's
operating threshold is selected on sao_paulo ``dev_select``, then both arms are compared at
their own thresholds on the open pool (laurens_mapillary + bayonne) with the paired pano
bootstrap of the macro F1 difference (2,000 draws, seed 276). The zero-shot+confidence arm
and its thresholds are Step 5's. Exploratory: Step 6 is a control, not an endpoint.

    python scripts/analysis/prompt_276_exemplars.py --cache-dir <main checkout>/.model_cache
    python scripts/analysis/prompt_276_exemplars.py --check --cache-dir ...

Reads the local detection cache (the exemplar legs are not published), so ``check_all``
runs it only with ``--allow local-cache``.
"""

import argparse
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
sys.path.insert(0, REPO_ROOT)

import prompt_276_heldout as H          # noqa: E402

C, D = H.C, H.D
OUT_JSON = os.path.join(H.OUT_DIR, "step6_exemplars.json")
OUT_MD = os.path.join(H.OUT_DIR, "step6_exemplars.md")
EXEMPLARS = "shared4"
ARMS = (("zs", None), ("shared4", EXEMPLARS))


def _r(v, nd=4):
    return round(float(v), nd)


def _prf(counts):
    tp, fp, tp_r, n_gt = counts.sum(0)
    p = tp / (tp + fp) if (tp + fp) else 0.0
    r = tp_r / n_gt if n_gt else 0.0
    return {"precision": _r(p), "recall": _r(r), "f1": _r(H.f1_from_counts(tp, fp, tp_r, n_gt)),
            "tp": int(tp), "fp": int(fp), "n_gt": int(n_gt)}


def build(cache_dir):
    rsq = H.radius_sq_for()
    cache = C.DetectionCache(cache_dir, enabled=True)
    args = H._compare_args(cache_dir)
    args.gemini_confidence = True
    args.gemini_thinking_level = None
    args.definition = None
    with open(os.path.join(REPO_ROOT, H.SPLIT_FILE), encoding="utf-8") as f:
        dev_select = json.load(f)["dev_select"]
    dev_records, dev_verdicts, _ = C.load_bundle(os.path.join(REPO_ROOT, "benchmark", H.DEV_CITY))
    dev_all = C.ground_truths_from_verdicts(dev_records, dev_verdicts)
    dev_gts = {p: dev_all[p] for p in dev_select}
    pool_gts = {s: H.load_split_gts(s)[1] for s in H.OPEN_POOL}

    models = []
    for model_id, short in H.MODELS:
        row = {"model": model_id, "short": short, "arms": {}}
        counts = {}
        for arm, exemplars in ARMS:
            args.gemini_exemplars = exemplars
            label, det = D.build_detector("gemini", model_id, dev_records, args)
            sig = det.signature()
            pts, missing = H.cached_points(cache, label, sig, H.DEV_CITY, dev_select)
            assert not missing, (short, arm, "dev_select", len(missing))
            thr, _, _ = H.select_threshold(pts, dev_gts, rsq)
            a = {"threshold": thr,
                 "dev_select": _prf(H.pano_counts(pts, dev_gts, rsq, thr)),
                 "dev_select_raw": _prf(H.pano_counts(pts, dev_gts, rsq, 0.0)),
                 "open": {}}
            counts[arm] = {}
            for s in H.OPEN_POOL:
                p2, missing = H.cached_points(cache, label, sig, s, list(pool_gts[s]))
                assert not missing, (short, arm, s, len(missing))
                counts[arm][s] = H.pano_counts(p2, pool_gts[s], rsq, thr)
                a["open"][s] = _prf(counts[arm][s])
            a["open_macro_f1"] = _r(np.mean([a["open"][s]["f1"] for s in H.OPEN_POOL]))
            row["arms"][arm] = a
        d, lo, hi, p = H.paired_bootstrap(counts["shared4"], counts["zs"],
                                          np.random.default_rng(H.SEED))
        row["open_macro_delta_f1"] = _r(d)
        row["ci95"] = [_r(lo), _r(hi)]
        row["p"] = _r(p)
        row["dev_select_delta_f1"] = _r(row["arms"]["shared4"]["dev_select"]["f1"]
                                        - row["arms"]["zs"]["dev_select"]["f1"])
        models.append(row)
    return {"exemplars": EXEMPLARS, "pool": list(H.OPEN_POOL), "draws": H.DRAWS,
            "seed": H.SEED, "models": models}


def render_md(res):
    lines = ["# #276 Step 6: four in-context exemplar crops vs zero-shot (both with confidence)",
             "", "Generated by `scripts/analysis/prompt_276_exemplars.py`. Do not edit by hand.",
             "", "| Model | Arm | Threshold | dev_select P / R / F1 | "
             + " | ".join("%s P / R / F1" % s for s in res["pool"]) + " | Open macro F1 |",
             "|---|---|---|---|" + "---|" * (len(res["pool"]) + 1)]
    fmt = lambda x: "%.3f / %.3f / %.3f" % (x["precision"], x["recall"], x["f1"])  # noqa: E731
    for m in res["models"]:
        for arm in ("zs", "shared4"):
            a = m["arms"][arm]
            lines.append("| %s | %s | %.2f | %s | %s | %.3f |" % (
                m["model"], arm, a["threshold"], fmt(a["dev_select"]),
                " | ".join(fmt(a["open"][s]) for s in res["pool"]), a["open_macro_f1"]))
    lines += ["", "Exemplars minus zero-shot:", "",
              "| Model | dev_select dF1 | Open-pool macro dF1 | 95% interval | p |",
              "|---|---|---|---|---|"]
    for m in res["models"]:
        lines.append("| %s | %+.3f | %+.3f | %+.3f to %+.3f | %s |" % (
            m["model"], m["dev_select_delta_f1"], m["open_macro_delta_f1"],
            m["ci95"][0], m["ci95"][1], H.fmt_p(m["p"])))
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cache-dir", default=os.path.join(REPO_ROOT, ".model_cache"))
    ap.add_argument("--check", action="store_true",
                    help="regenerate and compare with the committed JSON instead of writing")
    args = ap.parse_args(argv)
    res = build(args.cache_dir)
    rel = os.path.relpath(OUT_JSON, REPO_ROOT).replace("\\", "/")
    if args.check:
        with open(OUT_JSON, encoding="utf-8") as f:
            committed = json.load(f)
        if committed != res:
            print("MISMATCH: %s does not reproduce from the cache" % rel)
            return 1
        print("OK: %s reproduces from the cache (%d models)" % (rel, len(res["models"])))
        return 0
    os.makedirs(H.OUT_DIR, exist_ok=True)
    with open(OUT_JSON, "w", encoding="utf-8", newline="\n") as f:
        json.dump(res, f, indent=1)
        f.write("\n")
    with open(OUT_MD, "w", encoding="utf-8", newline="\n") as f:
        f.write(render_md(res))
    print(render_md(res))
    return 0


if __name__ == "__main__":
    sys.exit(main())
